/** Portable newline and provenance smoke for generated B01D/B01E art metadata. */
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';

const manifest = JSON.parse(readFileSync('art-source/manifests/iona-b01d-candidate-v1.json', 'utf8'));
const b01e = JSON.parse(readFileSync('art-source/manifests/iona-b01e-candidate-v1.json', 'utf8'));
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
function checkPortableMetrics(candidate) {
  const metricBytes = readFileSync(candidate.frameMetricsModule.path);
  const metricText = metricBytes.toString('utf8');
  assert.ok(!metricBytes.includes(0x0d), `${candidate.candidateId} TypeScript metrics must use LF bytes only`);
  assert.equal(hash(metricBytes), candidate.frameMetricsModule.sha256, `${candidate.candidateId} manifest hash must match exact checked-out bytes`);
  // Model a Windows CRLF working copy and prove LF normalization restores the generated bytes.
  const simulatedCrlf = Buffer.from(metricText.replace(/\n/g, '\r\n'), 'utf8');
  const normalizedCrlf = Buffer.from(simulatedCrlf.toString('utf8').replace(/\r\n/g, '\n'), 'utf8');
  assert.deepEqual(normalizedCrlf, metricBytes, `${candidate.candidateId} CRLF normalization must reproduce the exact artifact`);
  assert.equal(hash(normalizedCrlf), candidate.frameMetricsModule.sha256, `${candidate.candidateId} normalized CRLF copy must retain its digest`);
  return hash(metricBytes);
}
const b01dMetricsHash = checkPortableMetrics(manifest);
const b01eMetricsHash = checkPortableMetrics(b01e);

const statusCounts = Object.fromEntries(['NEW_IMAGEGEN_POSE', 'UNCHANGED_REUSED'].map((status) => [
  status,
  manifest.runtimeFrames.filter((frame) => frame.candidateStatus === status).length,
]));
assert.deepEqual(statusCounts, { NEW_IMAGEGEN_POSE: 8, UNCHANGED_REUSED: 60 }, 'B01D source inventory changed unexpectedly');
assert.equal(manifest.runtimeFrames.length, 68, 'B01D candidate frame inventory changed unexpectedly');

console.log(`PASS: B01D source inventory ${statusCounts.NEW_IMAGEGEN_POSE} new / ${statusCounts.UNCHANGED_REUSED} reused / 68 total`);
const eStatusCounts = Object.fromEntries(['NEW_IMAGEGEN_POSE', 'UNCHANGED_REUSED'].map((status) => [
  status,
  b01e.runtimeFrames.filter((frame) => frame.candidateStatus === status).length,
]));
assert.deepEqual(eStatusCounts, { NEW_IMAGEGEN_POSE: 8, UNCHANGED_REUSED: 62 }, 'B01E source inventory changed unexpectedly');
assert.equal(b01e.runtimeFrames.length, 70, 'B01E candidate frame inventory changed unexpectedly');
console.log(`PASS: B01D metrics ${b01dMetricsHash}; B01E metrics ${b01eMetricsHash}; CRLF simulation restores both; B01E inventory ${eStatusCounts.NEW_IMAGEGEN_POSE} new / ${eStatusCounts.UNCHANGED_REUSED} reused / 70 total`);
